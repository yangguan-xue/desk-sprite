// UTF-8 变长字节解码函数
static inline uint32_t utf8_next_codepoint(const char** pstr) {
    if (!pstr || !*pstr || !**pstr) return 0;
    const unsigned char* s = (const unsigned char*)*pstr;
    uint32_t cp = 0;
    int len = 0;

    if (s[0] < 0x80) {
        cp = s[0];
        len = 1;
    } else if ((s[0] & 0xE0) == 0xC0) {
        if ((s[1] & 0xC0) == 0x80) {
            cp = ((s[0] & 0x1F) << 6) | (s[1] & 0x3F);
            len = 2;
        } else {
            cp = s[0];
            len = 1;
        }
    } else if ((s[0] & 0xF0) == 0xE0) {
        if ((s[1] & 0xC0) == 0x80 && (s[2] & 0xC0) == 0x80) {
            cp = ((s[0] & 0x0F) << 12) | ((s[1] & 0x3F) << 6) | (s[2] & 0x3F);
            len = 3;
        } else {
            cp = s[0];
            len = 1;
        }
    } else if ((s[0] & 0xF8) == 0xF0) {
        if ((s[1] & 0xC0) == 0x80 && (s[2] & 0xC0) == 0x80 && (s[3] & 0xC0) == 0x80) {
            cp = ((s[0] & 0x07) << 18) | ((s[1] & 0x3F) << 12) | ((s[2] & 0x3F) << 6) | (s[3] & 0x3F);
            len = 4;
        } else {
            cp = s[0];
            len = 1;
        }
    } else {
        cp = s[0];
        len = 1;
    }

    *pstr += len;
    return cp;
}

// 获取字形位图 (ASCII / 常用汉字 / 方框 □ 安全回退)
static inline const uint8_t* sim_get_glyph(uint32_t cp) {
    if (cp < 128) {
        return font8x8_basic[cp];
    }
    for (size_t i = 0; i < sizeof(g_custom_glyphs)/sizeof(g_custom_glyphs[0]); i++) {
        if (g_custom_glyphs[i].codepoint == cp) {
            return g_custom_glyphs[i].bitmap;
        }
    }
    // 未收录字符安全回退为方框 □ (SPEC-003 第 5 节)
    return glyph_box_8x8;
}

