"""Generate RGB565 sprite planes and independent 12px glyphs (Pillow required).

Download NotoSansSC[wght].ttf from google/fonts/ofl/notosanssc, then:
python tools/generate_sakura_assets.py --font path/to/NotoSansSC.ttf
"""
import argparse
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'firmware/src/ui/assets/sakura_assets.h'
UI_TEXT = '''剩余额度我在，慢慢来。你写代码，我陪你。安静陪你开会。明天也一起加油。
在线陪着你连接中离线休息时间专注有个好消息晚安演示过期等待数据额度已用尽确认提醒
请在客户端确认静音收到新通知做好啦辛苦了构建通过任务完成失败需要处理秒双击长按打开关闭
测试中文成功警告正在等待网络同步更新额度设备服务本地时间不可用通知详细摘要请查看客户端…□·'''

def array(name, ctype, values, width=16):
    rows = [', '.join(f'0x{v:04x}' if ctype=='uint16_t' else str(v) for v in values[i:i+width]) for i in range(0,len(values),width)]
    return f'static const {ctype} {name}[{len(values)}] = {{\n' + ',\n'.join(rows) + '\n};\n'

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--font', type=Path, required=True);args=parser.parse_args()
    font=ImageFont.truetype(str(args.font),12)
    if hasattr(font, 'set_variation_by_axes'):
        font.set_variation_by_axes([500])
    source=(ROOT/'firmware/src/ui/ui_sakura.c').read_text(encoding='utf-8')
    extra=''.join(re.findall(r'[\u3000-\u9fff\uff00-\uffef]',source))
    chars=sorted(set(chr(cp) for cp in range(32,127)) | set(UI_TEXT.replace('\n','')+extra))
    parts=['/* Generated by tools/generate_sakura_assets.py; Noto Sans SC, SIL OFL 1.1. */\n#include <stdint.h>\n']
    for kind in ['open','blink']:
        image=Image.open(ROOT/f'assets/concepts/sakura-green/idle-demo/idle-{kind}-128-source.png').convert('RGBA')
        assert image.size==(67,120)
        rgb=[];mask=[]
        for r,g,b,a in list(image.get_flattened_data() if hasattr(image,'get_flattened_data') else image.getdata()):
            rgb.append(((r>>3)<<11)|((g>>2)<<5)|(b>>3));mask.append(1 if a>=128 else 0)
        # Separate opacity plane allows every RGB565 color, including black.
        parts += [array(f'sakura_{kind}', 'uint16_t',rgb),array(f'sakura_{kind}_mask','uint8_t',mask,32)]
    parts.append('typedef struct { uint32_t cp; uint8_t width; uint16_t rows[12]; } sakura_glyph_t;\nstatic const sakura_glyph_t sakura_glyphs[] = {\n')
    for ch in chars:
        width=12 if ord(ch)>255 else 7
        im=Image.new('L',(12,12)); d=ImageDraw.Draw(im)
        # Top-align the em box, retaining the CJK baseline and punctuation placement.
        d.text((0,-3),ch,font=font,fill=255,stroke_width=0)
        rows=[sum(1<<x for x in range(width) if im.getpixel((x,y))>=100) for y in range(12)]
        parts.append('{0x%x, %d, {%s}},\n'%(ord(ch),width,','.join(hex(v) for v in rows)))
    parts.append('};\n');OUT.parent.mkdir(parents=True,exist_ok=True);OUT.write_text(''.join(parts),encoding='utf-8')
    license_path=args.font.parent/'OFL.txt'
    if license_path.exists(): (OUT.parent/'NotoSansSC-OFL.txt').write_bytes(license_path.read_bytes())
    print(f'{OUT}: {len(chars)} glyphs, original 67x120 sprites')
if __name__=='__main__':main()
